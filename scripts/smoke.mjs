import assert from 'node:assert/strict';
import { writeFile, mkdir } from 'node:fs/promises';
const base = process.argv[2] || 'http://localhost:3000';
const origin = new URL(base).origin;
async function json(path, body) {
  const response = await fetch(`${base}${path}`, body ? { method: 'POST', headers: { 'content-type': 'application/json', origin, 'sec-fetch-site': 'same-origin' }, body: JSON.stringify(body), signal: AbortSignal.timeout(60000) } : { signal: AbortSignal.timeout(60000) });
  const value = await response.json();
  assert.equal(response.ok, true, `${path}: ${JSON.stringify(value)}`);
  return value;
}
const health = await json('/api/health');
assert.ok(health.credentials.gateway, 'Gateway must be configured');
const conditions = await json('/api/conditions');
assert.equal(conditions.destinations.length, 3);
assert.ok(conditions.destinations.every(p => p.camera.status !== 'unavailable'));
const plan = await json('/api/agent', { message: 'Compare the beaches. I want the warmer option, easy walking, and gear under $120.', destinationId: 'cowells', budget: 120, owned: [] });
assert.equal(plan.engine, 'gateway');
assert.equal(plan.budget, 120);
const vision = await json('/api/vision', { image: conditions.destinations[0].camera.imageUrl, kind: 'conditions' });
assert.equal(vision.engine, 'gateway');
assert.ok(vision.description.length > 30);
const shop = await json('/api/shop?budget=120');
const kit = ['shell', 'daypack', 'bottle'].map(c => shop.products.filter(p => p.category === c && p.available === true).sort((a,b) => a.priceAmount-b.priceAmount)[0]);
assert.ok(kit.every(Boolean), 'One available item per category');
const amount = kit.reduce((sum,p) => sum+p.priceAmount,0);
assert.ok(amount <= 12000);
const receipt = await json('/api/checkout', { items: kit.map(p => ({ productId:p.productId, variantId:p.variantId, quantity:1 })), budget:120 });
assert.equal(receipt.demo, true);
assert.ok(receipt.totalAmount <= 12000);
const evaluation = await json('/api/evaluate', { destinationId:'cowells', budget:120, owned:[], products:kit.map(p=>({productId:p.productId,variantId:p.variantId})) });
assert.equal(evaluation.engine, 'jev');
assert.equal(evaluation.assessments.length,3);
const bottle = kit.find(p => p.category === 'bottle');
const image = await fetch(bottle.image, { signal:AbortSignal.timeout(15000) });
assert.ok(image.ok);
const bytes = Buffer.from(await image.arrayBuffer());
const mime = image.headers.get('content-type').split(';')[0];
assert.ok(bytes.length < 3*1024*1024);
const gear = await json('/api/vision', { image:`data:${mime};base64,${bytes.toString('base64')}`, kind:'gear' });
assert.equal(gear.category,'bottle');
const alternate = await json('/api/agent', {message:'Keep this beach and confirm my $120 gear budget.',destinationId:'cowells',budget:120,owned:[],forceFallback:true});
assert.equal(alternate.fallback,true);
const traces = [...(plan.trace||[]),...(vision.trace||[]),...(gear.trace||[]),...(evaluation.trace||[]),...(alternate.trace||[])];
const models = [...new Set(traces.filter(t=>t.status==='success').map(t=>t.model))];
assert.ok(models.length >= 3,`Expected actual calls to three models, got ${models.join(',')}`);
assert.ok(!JSON.stringify(traces).includes(bytes.toString('base64').slice(0,100)), 'Raw image bytes must not enter traces');
assert.ok(traces.some(t=>t.operation==='routing.skip-primary' && t.status==='local'));
await mkdir('artifacts',{recursive:true});
await writeFile('artifacts/sample-bottle.'+(mime.includes('png')?'png':'jpg'),bytes);
const proof = { checkedAt:new Date().toISOString(),base,plan:{engine:plan.engine,model:plan.model,latencyMs:plan.latencyMs,fallback:plan.fallback,reply:plan.reply},vision:{engine:vision.engine,model:vision.model,description:vision.description},gear:{engine:gear.engine,model:gear.model,category:gear.category,confidence:gear.confidence},evaluation:{engine:evaluation.engine,model:evaluation.model,latencyMs:evaluation.latencyMs,assessments:evaluation.assessments},models,traces:traces.map(t=>({model:t.model,operation:t.operation,status:t.status,durationMs:t.durationMs})),kit:kit.map(p=>({title:p.title,price:p.price,category:p.category})),receipt:{orderId:receipt.orderId,total:receipt.total,demo:receipt.demo} };
await writeFile('artifacts/smoke.json',JSON.stringify(proof,null,2));
console.log(JSON.stringify(proof,null,2));
